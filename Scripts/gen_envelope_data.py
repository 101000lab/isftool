#!/usr/bin/env python3
"""Generate Sources/ISFKit/EnvelopeData.swift from JSON Lines of {"t", "address", "value"}.

The input is VDMX's Audio Analysis captured over OSC, with one "/Filter N" address per band.

    Scripts/gen_envelope_data.py vdmx_mic.jsonl > Sources/ISFKit/EnvelopeData.swift

For each band in order: a UInt32 sample count, then per sample a UInt32 time in 0.1 ms and a Float32 value,
all little endian.
"""
import base64
import json
import re
import struct
import sys

bands = {}
with open(sys.argv[1]) as f:
    for line in f:
        if not line.strip():
            continue
        entry = json.loads(line)
        m = re.fullmatch(r"/Filter (\d+)", entry["address"])
        if m:
            bands.setdefault(int(m.group(1)), []).append((round(entry["t"] * 10000), entry["value"]))

data = bytearray()
for n in sorted(bands):
    samples = bands[n]
    data += struct.pack("<I", len(samples))
    for t, v in samples:
        data += struct.pack("<If", t, v)

encoded = base64.b64encode(bytes(data)).decode()
print("// Generated by Scripts/gen_envelope_data.py. Do not edit.")
print()
print('let envelopeData = """')
for i in range(0, len(encoded), 120):
    print(encoded[i:i + 120])
print('"""')
